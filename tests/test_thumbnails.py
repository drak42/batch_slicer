"""Tests for drawing preview pictures from G-code and adding them to it."""

import base64
import os
import re
import struct
import zlib
from pathlib import Path

import pytest

from batchslicer.services.thumbnails import (
    DEFAULT_SIZES,
    ThumbnailError,
    add_thumbnails,
    encode_png,
    extrusions,
    read_preview,
    render,
)


def _box_gcode(*, colour: str = "#F2754E", sizes: str | None = "300x300/PNG, 96x96/PNG") -> str:
    """Return G-code printing the walls of a 20 x 10 x 5 mm box, with a purge line and a brim."""
    lines = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer 2.5.2",
        "; HEADER_BLOCK_END",
        "",
        "M83",
        "G1 X0 Y0 E15",  # purge line: before any feature marker
        "G92 E0",
        ";TYPE:Brim",
        "G1 X-5 Y-5 E1",
    ]
    for layer in range(25):
        z = 0.2 * (layer + 1)
        lines += [
            f"G1 Z{z:.2f}",
            "G1 X100 Y100",  # travel
            ";TYPE:Outer wall",
            "G1 X120 Y100 E.5",
            "G1 X120 Y110 E.5",
            "G1 X100 Y110 E.5",
            "G1 X100 Y100 E.5",
            ";TYPE:Sparse infill",
            "G1 X120 Y110 E.5",
        ]
    lines += ["; CONFIG_BLOCK_START", f"; filament_colour = {colour}"]
    if sizes is not None:
        lines.append(f"; thumbnails = {sizes}")
    lines.append("; CONFIG_BLOCK_END")
    return "\n".join(lines) + "\n"


def _pictures(text: str) -> list[tuple[int, int, bytes, list[str]]]:
    """Return each picture block as (width, height, PNG bytes, base64 lines)."""
    found = []
    for match in re.finditer(r"; thumbnail begin (\d+)x(\d+) (\d+)\n(.*?); thumbnail end", text, re.S):
        lines = [line[2:] for line in match.group(4).splitlines()]
        data = "".join(lines)
        assert len(data) == int(match.group(3))
        found.append((int(match.group(1)), int(match.group(2)), base64.b64decode(data), lines))
    return found


def _png_size_and_pixels(png: bytes) -> tuple[int, int, bytes]:
    """Decode a PNG written by encode_png: its size and raw RGBA rows (with filter bytes)."""
    assert png.startswith(b"\x89PNG\r\n\x1a\n")
    width, height, depth, colour_type = struct.unpack(">IIBB", png[16:26])
    assert (depth, colour_type) == (8, 6)
    start = png.index(b"IDAT") + 4
    length = struct.unpack(">I", png[start - 8 : start - 4])[0]
    return width, height, zlib.decompress(png[start : start + length])


def test_only_the_models_extrusions_are_drawn() -> None:
    """Purge lines, travel, brim and hidden infill are left out; walls are kept."""
    segments = list(extrusions(_box_gcode().splitlines()))

    assert len(segments) == 25 * 4
    assert segments[0] == (100.0, 100.0, 120.0, 100.0, 0.2, 0)
    assert all(100 <= x <= 120 and 100 <= y <= 110 for _, _, x, y, _, _ in segments)


def test_absolute_extrusion_relative_moves_and_arcs() -> None:
    """M82 with G92 resets, G91 moves and G2/G3 arcs are followed."""
    lines = [
        "M82", ";TYPE:Outer wall", "G1 X10 Y0 E1", "G1 X20 Y0 E1",  # second move does not extrude
        "G92 E0", "G1 X30 Y0 E0.5", "G91", "G1 X5 E1", "G90",
        "G2 X35 Y10 I0 J5 E2",  # half circle, clockwise around (35, 5)
    ]

    segments = list(extrusions(lines))

    assert segments[0] == (0.0, 0.0, 10.0, 0.0, 0.0, 0)
    assert segments[1] == (20.0, 0.0, 30.0, 0.0, 0.0, 0)
    assert segments[2] == (30.0, 0.0, 35.0, 0.0, 0.0, 0)
    arc = segments[3:]
    assert len(arc) >= 2
    assert arc[-1][2:4] == (35.0, 10.0)
    assert min(x for _, _, x, _, _, _ in arc) < 31  # went round the left side (clockwise)


def test_pictures_are_inserted_after_the_header(tmp_path: Path) -> None:
    """Each asked-for size is added as a valid PNG, in 80-column lines, after the header."""
    path = tmp_path / "box.gcode"
    original = _box_gcode()
    path.write_text(original)
    path.chmod(0o644)

    result = add_thumbnails(path)

    text = path.read_text()
    assert result.added == ((300, 300), (96, 96))
    assert text.startswith("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.5.2\n; HEADER_BLOCK_END\n\n; THUMBNAIL_BLOCK_START\n;\n")
    assert text.replace(text[text.index("\n; THUMBNAIL_BLOCK_START"): text.rindex("; THUMBNAIL_BLOCK_END\n\n") + 23], "") == original
    pictures = _pictures(text)
    assert [(width, height) for width, height, _, _ in pictures] == [(300, 300), (96, 96)]
    for width, height, png, lines in pictures:
        assert _png_size_and_pixels(png)[:2] == (width, height)
        assert all(len(line) <= 78 for line in lines)
    if os.name != "nt":  # Windows has no Unix permissions to keep
        assert path.stat().st_mode & 0o777 == 0o644
    assert not list(tmp_path.glob(".*.tmp"))


def test_picture_shows_the_part_in_the_filament_colour(tmp_path: Path) -> None:
    """The part is drawn in shades of its filament colour on a transparent background."""
    segments = list(extrusions(_box_gcode().splitlines()))

    pixels = render(segments, 64, 64, (0xF2, 0x75, 0x4E))

    alphas = pixels[3::4]
    assert alphas[0] == 0  # corner: background
    drawn = [i for i, alpha in enumerate(alphas) if alpha == 255]
    assert len(drawn) > 64 * 64 // 5
    red, green, blue = (pixels[drawn[len(drawn) // 2] * 4 + k] for k in range(3))
    assert red > green > blue


def test_files_are_left_alone_when_pictures_are_not_wanted_or_present(tmp_path: Path) -> None:
    """A second run adds nothing; no PNG sizes, or no toolpaths, add nothing either."""
    path = tmp_path / "box.gcode"
    path.write_text(_box_gcode())
    add_thumbnails(path)
    once = path.read_text()
    assert add_thumbnails(path).reason == "already has preview pictures"
    assert path.read_text() == once

    for text, reason in (
        (_box_gcode(sizes=""), "asks for no PNG"),
        (_box_gcode(sizes="300x300/JPG"), "asks for no PNG"),
        ("; HEADER_BLOCK_END\nG28\n", "no model toolpaths"),
    ):
        path.write_text(text)
        result = add_thumbnails(path)
        assert not result.added and reason in result.reason
        assert path.read_text() == text


def test_default_sizes_when_the_gcode_does_not_say(tmp_path: Path) -> None:
    """Without a thumbnails setting the usual sizes are used; a file without header gets them first."""
    path = tmp_path / "box.gcode"
    text = _box_gcode(sizes=None).replace("; HEADER_BLOCK_END\n", "").replace("; HEADER_BLOCK_START\n", "")
    path.write_text(text)

    assert add_thumbnails(path).added == DEFAULT_SIZES
    assert path.read_text().startswith("; THUMBNAIL_BLOCK_START\n")


def test_unreadable_file_and_bad_sizes_are_errors(tmp_path: Path) -> None:
    """Problems are raised as ThumbnailError for the caller to log."""
    with pytest.raises(ThumbnailError, match="Cannot read"):
        add_thumbnails(tmp_path / "missing.gcode")
    with pytest.raises(ThumbnailError, match="Unsupported picture size"):
        render([(0, 0, 1, 1, 0, 0)], 0, 10)


def test_png_encoding_round_trips() -> None:
    """encode_png writes rows with no filter, as standard PNG readers expect."""
    pixels = bytes([255, 0, 0, 255, 0, 0, 255, 128])  # 2x1: red, half-transparent blue

    width, height, raw = _png_size_and_pixels(encode_png(pixels, 2, 1))

    assert (width, height) == (2, 1)
    assert raw == b"\x00" + pixels


def test_tool_changes_colour_the_picture() -> None:
    """Moves after T1 belong to filament slot 1 and are drawn in its colour."""
    lines = [";TYPE:Outer wall", "T0", "G1 X0 Y0 F600", "G1 X10 Y0 E1", "T1 ; change", "G1 X10 Y10 E2",
             "T255", "G1 X0 Y10 E3", "M620 S1A", "G1 X0 Y0 E4"]

    segments = list(extrusions(lines))

    assert [segment[5] for segment in segments] == [0, 1, 1, 1]


def test_each_filament_has_its_colour_in_the_picture() -> None:
    """A two-colour part shows both colours; a slot without a colour uses the last one."""
    left = [(x, 0.0, x, 20.0, z / 5, 0) for x in range(0, 10) for z in range(5)]
    right = [(x, 0.0, x, 20.0, z / 5, 1) for x in range(10, 20) for z in range(5)]

    pixels = render(left + right, 48, 48, [(0xFF, 0x00, 0x00), (0x00, 0x00, 0xFF)])

    colours = {
        (pixels[i], pixels[i + 1], pixels[i + 2]) for i in range(0, len(pixels), 4) if pixels[i + 3] == 255
    }
    assert any(red > 150 and blue < 80 for red, _, blue in colours)
    assert any(blue > 150 and red < 80 for red, _, blue in colours)
    only_one = render(left + right, 48, 48, [(0x00, 0xFF, 0x00)])
    assert all(only_one[i] < 120 for i in range(0, len(only_one), 4) if only_one[i + 3] == 255)


def test_filament_colours_are_read_for_every_slot(tmp_path: Path) -> None:
    """add_thumbnails colours by the G-code's filament_colour list, alpha included."""
    from batchslicer.services.thumbnails import _filament_colours

    assert _filament_colours("; filament_colour = #000000;#FFFFFFFF;bad\n") == [
        (0, 0, 0), (255, 255, 255), (0x9A, 0x9F, 0xA6),
    ]
    assert _filament_colours("; nothing\n") == [(0x9A, 0x9F, 0xA6)]


def test_the_largest_picture_is_read_back(tmp_path: Path) -> None:
    """read_preview returns the biggest PNG in the G-code, or None without pictures."""
    path = tmp_path / "box.gcode"
    path.write_text(_box_gcode())
    assert read_preview(path) is None

    add_thumbnails(path)

    png = read_preview(path)
    assert png is not None
    assert _png_size_and_pixels(png)[:2] == (300, 300)
    assert read_preview(tmp_path / "missing.gcode") is None
